public class Config {
    String uri;
    String user;
    String pass;
    public String getURI() {
        return uri;
    }
    public String getUser() {
        return user;
    }
    public String getPass() {
        return pass;
    }
    public void setURI(String uri) {
        this.uri = uri;
    }
    public void setUser(String user) {
        this.user = user;
    }
    public void setPass(String pass) {
        this.pass = pass;
    }
}
